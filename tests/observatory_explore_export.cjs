"use strict";
const assert=require("node:assert/strict");
const X=require("../observatory-explore/export.js");
const P=require("../observatory-explore/report.js");
const E=require("../observatory-explore/engine.js");
const A=require("../observatory-explore/analysis.js");
const q={work:["w2","w1"],region:["Piemonte"],year:["2026"],from:"2026-01-01",type:"festival",temporal:"future"};
const st={preset:"rare",group:"region",metric:"venues",order:"asc",secondary:false,view:"performances"};
const decoded=X.decode(X.encode(q,st));
assert.deepEqual(decoded.q.work,["w1","w2"]);
assert.equal(decoded.q.region[0],"Piemonte");
assert.equal(decoded.q.from,q.from);
assert.deepEqual(decoded.state,st);
assert.equal(X.decode(""),null);
assert.throws(()=>X.decode("v=2"),/Versione/);
assert.throws(()=>X.decode("v=1&group=unknown"),/Impostazione/);
const csv=X.csv([["id","ID"],["label","Città"]],[{id:"a",label:'Torino; "centro"'},{id:"b",label:" =2+2"}]);
assert.ok(csv.startsWith("\uFEFF"));
assert.ok(csv.includes('"Torino; ""centro"""'));
assert.ok(csv.includes('"\' =2+2"'));
const rows=E.normalize([{id:"r1",staging_id:"s1",venue_id:"v1",work_id:"w1",title:"L'opera è qui",composer:"Autore",venue:"Teatro",municipality:"Città",region:"Piemonte",local_date:"2026-01-01",status:"announced",staging_url:"/torino/teatro/opera/"}],[]);
const groups=A.compare(rows,"work"),counts=E.summary(rows);
assert.equal(X.performanceRecords(rows,new Map([["r1",["https://example.org"]]]))[0].sources,"https://example.org");
assert.equal(X.productionRecords(rows)[0].performances,1);
const input={reviewedOn:"2026-11-26",generatedOn:"2026-11-26",context:"Città: Torino; l'opera è qui",groupLabel:"Opera",metricLabel:"Recite",metric:"performances",counts,labels:A.metrics,groups,months:A.monthly(rows),regions:A.compare(rows,"region"),productions:X.productionRecords(rows),performances:X.performanceRecords(rows),view:"performances",secondary:true};
(async()=>{
 const pdf=P.create(input);
 assert.equal(pdf.type,"application/pdf");
 const bytes=Buffer.from(await pdf.arrayBuffer()),raw=bytes.toString("latin1");
 assert.ok(raw.startsWith("%PDF-1.4"));
 assert.ok(raw.includes("Dettaglio recite"));
 assert.ok(raw.includes("Città"));
 assert.ok(raw.includes("è qui"));
 assert.ok(raw.includes("startxref"));
 const off=Number(raw.match(/startxref\n(\d+)/)[1]);assert.equal(raw.slice(off,off+4),"xref");
 const long=P.create({...input,view:"productions",productions:Array.from({length:100},()=>input.productions[0])});
 assert.ok(long.size>pdf.size);
 console.log("Explore PDF, CSV and URL tests passed");
})().catch(err=>{console.error(err);process.exitCode=1});
